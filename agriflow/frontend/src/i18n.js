const STR = { en, hi, gu };

export function translate(lang, key, vars = {}) {
  const table = STR[lang] || STR.en;
  const template = table[key] ?? STR.en[key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '');
}

export function errorText(lang, error) {
  const code = error?.code || 'SERVER';
  return translate(lang, `err_${code}`);
}
